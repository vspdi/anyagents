import loaderSource from 'virtual:opencode-loader';
import { detailOf, type Plugin } from './schemas.js';

/** Skill metadata the OpenCode 2 loader registers without reparsing YAML. */
export interface OpencodeSkill {
  id: string;
  name: string;
  description: string;
}
export interface OpencodePackageInput {
  id: string;
  plugin: Plugin;
  skills: OpencodeSkill[];
  /** Native OpenCode MCP servers, enabled ones only. */
  servers: Record<string, Record<string, unknown>>;
  /** Packaged top-level entries, such as `skills` or `assets`. */
  entries: string[];
}

export const OPENCODE_DATA_FILE = 'anyagents.opencode.json';
export const OPENCODE_ENTRY_FILE = 'index.js';

/**
 * Fixed loader for every generated package, embedded from
 * `opencode-loader.mjs` at build time so it is linted and tested as real code.
 */
export const opencodeLoader = `// Generated by AnyAgents. Edit the canonical plugin definition instead.
${loaderSource}`;

const replaceDeep = (value: unknown): unknown =>
  typeof value === 'string'
    ? value.replaceAll('${PLUGIN_ROOT}', '{plugin:root}')
    : Array.isArray(value)
      ? value.map(replaceDeep)
      : value && typeof value === 'object'
        ? Object.fromEntries(
            Object.entries(value).map(([key, item]) => [
              key,
              replaceDeep(item),
            ]),
          )
        : value;

const json = (value: unknown): Buffer =>
  Buffer.from(`${JSON.stringify(value, null, 2)}\n`);

/** Generated files of one OpenCode package, relative to its root. */
export const opencodePackage = ({
  id,
  plugin,
  skills,
  servers,
  entries,
}: OpencodePackageInput): { local: string; content: Buffer }[] => {
  const name = detailOf(plugin, 'opencode')?.packageName;
  const manifest = {
    name: typeof name === 'string' ? name : id,
    version: plugin.release,
    description: plugin.description,
    type: 'module',
    main: `./${OPENCODE_ENTRY_FILE}`,
    exports: { '.': `./${OPENCODE_ENTRY_FILE}` },
    files: [
      OPENCODE_ENTRY_FILE,
      OPENCODE_DATA_FILE,
      ...[...entries].sort((a, b) => a.localeCompare(b)),
    ],
    author: plugin.author,
    ...(plugin.homepage ? { homepage: plugin.homepage } : {}),
    ...(plugin.repository ? { repository: plugin.repository } : {}),
    ...(plugin.license ? { license: plugin.license } : {}),
    keywords: [
      ...new Set(['opencode', 'opencode-plugin', ...(plugin.keywords ?? [])]),
    ],
  };
  return [
    { local: 'package.json', content: json(manifest) },
    {
      local: OPENCODE_ENTRY_FILE,
      content: Buffer.from(opencodeLoader),
    },
    {
      local: OPENCODE_DATA_FILE,
      content: json({
        id,
        skills,
        mcp: replaceDeep(servers),
      }),
    },
  ];
};
